    private void assertImportWaitsForRedirectGraphLock(
            JdbcTemplate jdbc,
            PlacePilotImportService importer,
            ObjectNode envelope,
            UUID runId,
            UUID placeId
    ) throws Exception {
        ExecutorService executor = Executors.newFixedThreadPool(2);
        CountDownLatch releaseTerminalBlocker = new CountDownLatch(1);
        try (Connection blocker = jdbc.getDataSource().getConnection()) {
            blocker.setAutoCommit(false);
            try (PreparedStatement lock = blocker.prepareStatement(
                    "select pg_advisory_xact_lock(5517, 917)")) {
                lock.executeQuery().close();
            }
            Future<PlacePilotImportService.ImportResult> importing =
                    executor.submit(() -> importAuthorized(importer, envelope));
            long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            while (System.nanoTime() < deadline && !importing.isDone()
                    && count(jdbc, "select count(*) from place_source_records where sync_run_id = ?",
                    runId) < 2) {
                Thread.sleep(25);
            }
            assertThat(count(jdbc,
                    "select count(*) from place_source_records where sync_run_id = ?", runId))
                    .isEqualTo(2);
            assertThat(importing.isDone()).isFalse();
            assertThat(count(jdbc, "select count(*) from places where id = ?", placeId)).isZero();
            deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            while (System.nanoTime() < deadline && count(jdbc, """
                    select count(*) from pg_locks
                     where locktype = 'advisory' and not granted
                    """) < 1) {
                Thread.sleep(25);
            }
            assertThat(count(jdbc, """
                    select count(*) from pg_locks
                     where locktype = 'advisory' and not granted
                    """)).isGreaterThanOrEqualTo(1);

            CountDownLatch terminalWaitStarted = new CountDownLatch(1);
            CountDownLatch terminalLockAcquired = new CountDownLatch(1);
            Future<Void> terminalBlocker = executor.submit(() -> {
                try (Connection terminal = jdbc.getDataSource().getConnection()) {
                    terminal.setAutoCommit(false);
                    terminalWaitStarted.countDown();
                    try (PreparedStatement lock = terminal.prepareStatement(
                            "select pg_advisory_xact_lock(5517, 917)")) {
                        lock.executeQuery().close();
                    }
                    terminalLockAcquired.countDown();
                    if (!releaseTerminalBlocker.await(30, TimeUnit.SECONDS)) {
                        throw new IllegalStateException("terminal graph-lock blocker timed out");
                    }
                    terminal.commit();
                }
                return null;
            });
            assertThat(terminalWaitStarted.await(5, TimeUnit.SECONDS)).isTrue();
            deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            while (System.nanoTime() < deadline && count(jdbc, """
                    select count(*) from pg_locks
                     where locktype = 'advisory' and not granted
                    """) < 2) {
                Thread.sleep(25);
            }
            assertThat(count(jdbc, """
                    select count(*) from pg_locks
                     where locktype = 'advisory' and not granted
                    """)).isGreaterThanOrEqualTo(2);
            blocker.commit();

            assertThat(terminalLockAcquired.await(10, TimeUnit.SECONDS)).isTrue();
            assertThat(importing.isDone()).isFalse();
            assertThat(jdbc.queryForObject("select catalog_status from places where id = ?",
                    String.class, placeId)).isEqualTo("PROVISIONAL");
            assertThat(jdbc.queryForObject("select status from place_provider_sync_runs where id = ?",
                    String.class, runId)).isEqualTo("STARTED");
            releaseTerminalBlocker.countDown();
            terminalBlocker.get(30, TimeUnit.SECONDS);
            assertThat(importing.get(30, TimeUnit.SECONDS).status()).isEqualTo("SUCCEEDED");
            assertThat(jdbc.queryForObject("select catalog_status from places where id = ?",
                    String.class, placeId)).isEqualTo("ACTIVE");
        } finally {
            releaseTerminalBlocker.countDown();
            executor.shutdownNow();
        }
    }

    private void assertConcurrentRedirectCycleIsSerialized(
            JdbcTemplate jdbc,
            UUID syncRunId,
            OffsetDateTime occurredAt
    ) throws Exception {
        ExecutorService executor = Executors.newSingleThreadExecutor();
        try (Connection first = jdbc.getDataSource().getConnection();
             Connection second = jdbc.getDataSource().getConnection()) {
            first.setAutoCommit(false);
            second.setAutoCommit(false);
            try (PreparedStatement update = first.prepareStatement("""
                    update place_external_refs
                       set status = 'MERGED', redirected_provider = 'OVERTURE',
                           redirected_external_id = 'o-1', last_seen_at = ?,
                           last_sync_run_id = ?
                     where provider = 'OVERTURE' and external_id = 'o-2'
                    """)) {
                update.setObject(1, occurredAt);
                update.setObject(2, syncRunId);
                assertThat(update.executeUpdate()).isEqualTo(1);
            }

            CountDownLatch secondStarted = new CountDownLatch(1);
            Future<Void> competing = executor.submit(() -> {
                secondStarted.countDown();
                try (PreparedStatement update = second.prepareStatement("""
                        update place_external_refs
                           set status = 'MERGED', redirected_provider = 'OVERTURE',
                               redirected_external_id = 'o-2', last_seen_at = ?,
                               last_sync_run_id = ?
                         where provider = 'OVERTURE' and external_id = 'o-1'
                        """)) {
                    update.setObject(1, occurredAt.plusNanos(1));
                    update.setObject(2, syncRunId);
                    update.executeUpdate();
                }
                second.commit();
                return null;
            });
            assertThat(secondStarted.await(5, TimeUnit.SECONDS)).isTrue();
            assertThat(competing.isDone()).isFalse();
            first.commit();
            Throwable competingFailure = catchThrowable(competing::get);
            assertThat(competingFailure).isInstanceOf(ExecutionException.class);
            assertPostgresCheckViolation(competingFailure,
                    "external reference redirect cycle is not allowed");
            second.rollback();
        } finally {
            executor.shutdownNow();
            assertThat(executor.awaitTermination(5, TimeUnit.SECONDS)).isTrue();
        }
    }

