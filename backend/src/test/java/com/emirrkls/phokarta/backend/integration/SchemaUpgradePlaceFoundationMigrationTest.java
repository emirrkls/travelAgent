    private void selectStage(ObjectNode manifest, String stage) {
        manifest.put("canary_stage", stage);
        int eligibleCount = 0;
        for (JsonNode candidate : manifest.path("candidates")) {
            if (candidate.path("canary_eligible").asBoolean(false)) eligibleCount++;
        }
        int first = switch (stage) {
            case "STAGE_1" -> 1;
            case "STAGE_2" -> 101;
            case "STAGE_3" -> 501;
            default -> throw new IllegalArgumentException("invalid test stage");
        };
        int last = switch (stage) {
            case "STAGE_1" -> Math.min(100, eligibleCount);
            case "STAGE_2" -> Math.min(500, eligibleCount);
            case "STAGE_3" -> eligibleCount;
            default -> throw new IllegalArgumentException("invalid test stage");
        };
        for (JsonNode value : manifest.path("candidates")) {
            ObjectNode candidate = (ObjectNode) value;
            int rank = candidate.path("selection_rank").asInt(-1);
            candidate.put("selected_for_stage", rank >= first && rank <= last);
        }
    }

    private void refreshDerivedManifest(
            PlacePilotImportService importer,
            ObjectNode manifest
    ) {
        Map<String, String> remappedSourceIds = new HashMap<>();
        for (JsonNode value : manifest.path("source_records")) {
            ObjectNode source = (ObjectNode) value;
            String previous = source.path("source_record_id").asText();
            String deterministic = sourceUuid(
                    source.path("provider").asText(), source.path("external_id").asText(),
                    source.path("method_version").asText(), source.path("source_hash").asText())
                    .toString();
            source.put("source_record_id", deterministic);
            remappedSourceIds.put(previous, deterministic);
        }
        for (JsonNode value : manifest.path("candidates")) {
            ObjectNode candidate = (ObjectNode) value;
            ArrayNode sourceIds = (ArrayNode) candidate.path("source_record_ids");
            for (int index = 0; index < sourceIds.size(); index++) {
                String previous = sourceIds.get(index).asText();
                String deterministic = remappedSourceIds.get(previous);
                if (deterministic != null) {
                    sourceIds.remove(index);
                    sourceIds.insert(index, deterministic);
                }
            }
            if (candidate.path("canary_eligible").asBoolean(false)) {
                candidate.put("canonical_place_id",
                        placeUuid(candidate.path("candidate_id").asText()).toString());
            }
        }
        refreshCandidateHashes(importer, manifest);
    }

